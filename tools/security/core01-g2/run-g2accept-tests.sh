#!/usr/bin/env bash
# CORE-01 G2 — run HTTP authority tests against the independent G2 acceptance
# cluster (port 55460, daleel-d1-g2accept-pg).
#
# Must be run AFTER build-g2accept-cluster.sh has completed successfully.
# Sources g2accept-cluster-identity.env to obtain the cluster sysid and secrets.
#
# Usage:  run-g2accept-tests.sh '<phpunit --filter expression>'
#   e.g.  run-g2accept-tests.sh 'TenantAuthorityHttpFaultInjectionTest'
#         run-g2accept-tests.sh 'TenantAuthorityFaultInjectionTest|TenantAuthorityConcurrencyTest'
#
# The in-test G2AcceptClusterGuard re-verifies G2_ACCEPT_CLUSTER_SYSID + scope
# live before any write. Guard refuses forbidden ports and protected databases
# regardless of ENV.

set -euo pipefail

FILTER="${1:?usage: run-g2accept-tests.sh '<--filter expression>'}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
API_DIR="$(cd "${SCRIPT_DIR}/../../.." && pwd)"  # daleel-crm-api
readonly IDENTITY_FILE="${SCRIPT_DIR}/g2accept-cluster-identity.env"
readonly ACCEPT_CONTAINER="daleel-d1-g2accept-pg"
readonly PHP_IMAGE="daleel-core01-php-local:20261028"

# ── Source cluster identity (generated by build-g2accept-cluster.sh) ──────────
if [ ! -f "${IDENTITY_FILE}" ]; then
    echo "ERROR: ${IDENTITY_FILE} not found." >&2
    echo "       Run build-g2accept-cluster.sh first." >&2
    exit 1
fi
# shellcheck source=/dev/null
source "${IDENTITY_FILE}"

# ── Verify container is running ───────────────────────────────────────────────
if ! docker ps --format '{{.Names}}' | grep -qx "${ACCEPT_CONTAINER}"; then
    echo "ERROR: container ${ACCEPT_CONTAINER} is not running." >&2
    echo "       Start it with: docker start ${ACCEPT_CONTAINER}" >&2
    exit 1
fi

# ── Derive the DB-side signing key from the live cluster ─────────────────────
# This keeps the PHP-side signing key aligned with what the DB stores, so tests
# that verify DB-side signatures cannot drift from the cluster.
SIGNING_KEY_HEX="$(docker exec "${ACCEPT_CONTAINER}" \
    psql -U postgres -d "${G2_ACCEPT_DB}" -tAc \
    "SELECT encode(secret,'hex') FROM core01_sql_signing_keys WHERE id=1 AND status='ACTIVE'" \
    2>/dev/null | tr -d '[:space:]')"

# Fall back to the build-time key if the DB key is not yet readable.
if [ -z "${SIGNING_KEY_HEX}" ]; then
    SIGNING_KEY_HEX="${G2_ACCEPT_SIGNING_KEY}"
fi

MSYS_NO_PATHCONV=1 docker run --rm \
    --network "container:${ACCEPT_CONTAINER}" \
    -v        "${API_DIR}:/app" \
    -w        /app \
    -e APP_ENV=testing \
    -e DB_CONNECTION=pgsql \
    -e DB_HOST=127.0.0.1    -e DB_PORT=5432 \
    -e DB_DATABASE="${G2_ACCEPT_DB}" \
    -e DB_USERNAME=postgres \
    -e DB_PASSWORD=g2accept-trust-auth \
    -e TENANT_AUTH_DB_HOST=127.0.0.1     -e TENANT_AUTH_DB_PORT=5432 \
    -e TENANT_AUTH_DB_DATABASE="${G2_ACCEPT_DB}" \
    -e TENANT_AUTH_DB_USERNAME=dl_tauth \
    -e TENANT_AUTH_DB_PASSWORD=g2accept-trust-auth \
    -e TENANT_HOST_DB_HOST=127.0.0.1     -e TENANT_HOST_DB_PORT=5432 \
    -e TENANT_HOST_DB_DATABASE="${G2_ACCEPT_DB}" \
    -e TENANT_HOST_DB_USERNAME=dl_host \
    -e TENANT_HOST_DB_PASSWORD=g2accept-trust-auth \
    -e TENANT_RUNTIME_DB_HOST=127.0.0.1  -e TENANT_RUNTIME_DB_PORT=5432 \
    -e TENANT_RUNTIME_DB_DATABASE="${G2_ACCEPT_DB}" \
    -e TENANT_RUNTIME_DB_USERNAME=dl_core_truntime \
    -e TENANT_RUNTIME_DB_PASSWORD="${G2_ACCEPT_RUNTIME_PASSWORD}" \
    -e G2_ACCEPT_DB="${G2_ACCEPT_DB}" \
    -e G2_ACCEPT_PORT=5432 \
    -e G2_ACCEPT_HOST="${G2_ACCEPT_HOST}" \
    -e G2_ACCEPT_SUPERUSER="${G2_ACCEPT_SUPERUSER}" \
    -e G2_ACCEPT_CLUSTER_SYSID="${G2_ACCEPT_CLUSTER_SYSID}" \
    -e CORE01_SESSION_BINDING_KEY="${G2_ACCEPT_SESSION_BINDING_KEY}" \
    -e CORE01_PROVIDER_PROOF_KEY="${G2_ACCEPT_PROVIDER_PROOF_KEY}" \
    -e CORE01_SQL_SIGNING_KEY="${SIGNING_KEY_HEX}" \
    -e CORE01_SQL_SIGNING_KEY_GENERATION=1 \
    -e CORE_SQL_TRUSTED_TENANT_LOGIN=dl_core_truntime \
    -e CORE_SQL_LEGACY_TENANT_LOGIN=daleel_b10b_tenant_runtime \
    "${PHP_IMAGE}" \
    php artisan test --filter "${FILTER}"
